<h1>Переменные в PHP</h1>
<h2>В PHP для хранения данных есть специальный инструмент — переменные. Их часто сравнивают с коробками.
    В коробки можно складывать физические предметы, а на переменные — "наклеивать" метки (имена), чтобы описывать их
    содержимое (значение).</h2>
<h2>Правила создания переменных в PHP:</h2>
<ul>
    <li>Имя переменной должно начинаться со знака доллара $.</li>
    <li>Имя может содержать буквы, цифры и символ подчеркивания _.</li>
    <li>Запрещено использовать специальные символы (например, @).</li>
</ul>
<ol>
    <li>Первым символом после $ может быть буква или подчеркивание _, но не цифра.</li>
</ol>
<h2>Рекомендации по именованию переменных (best practices):</h2>
<ol>
    <li>Быть описательными. Имя должно ясно указывать, что хранит переменная. Например, $totalPrice (общая цена) —
        хорошо, $tp — плохо.</li>
    <li>Избегать однобуквенных имен (кроме счетчиков в циклах).</li>
    <li>Быть последовательными в выбранном стиле написания.</li>
</ol>

<p>Избегать общих имен. Например, $data — плохо, $userData или $productList — хорошо.</p>

<h2>Стили написания для имен из нескольких слов:</h2>

<h3>camelCase (верблюжий регистр):</h3>
<p>Первое слово с маленькой буквы, последующие — с большой. Например, $userAge.</p>
<p>Каждое слово с большой буквы. Например, $UserAge.</p>
<h3>snake_case (змеиный регистр):</h3>
<p>Все слова в нижнем регистре, разделены подчеркиванием. Например, $user_age.</p>
Большинство PHP-разработчиков предпочитают использовать camelCase для переменных. Главное — быть последовательным. В
этом курсе мы будем использовать camelCase.